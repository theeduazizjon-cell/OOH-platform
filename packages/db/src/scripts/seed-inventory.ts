/**
 * Local development: a realistic inventory volume for the map (12-roadmap.md M5 exit criterion:
 * "20k seeded assets pan/zoom smoothly"). Adds assets to the demo company until it has SEED_ASSETS
 * generated ones (default 20 000), spread around Romanian cities, with mounts and faces from each
 * type's template. Safe to re-run; `--remove` deletes the generated assets that nothing refers to.
 *
 *   pnpm db:seed && pnpm db:seed:inventory
 */
const MARKER = 'Generated by db:seed:inventory';

