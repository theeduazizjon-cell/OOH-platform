/** Share of each provisioned type key. */
const TYPE_MIX: Record<string, number> = { pole: 50, billboard: 25, prism: 8, mesh: 7, wall: 7, other: 3 };

/** Splits `total` by weights, rounding so the parts add up exactly. */
export function apportion(total: number, weights: readonly number[]): number[] {
  const sum = weights.reduce((a, b) => a + b, 0);
  const raw = weights.map((w) => (total * w) / sum);
  const parts = raw.map(Math.floor);
  const order = raw.map((r, i) => [r - Math.floor(r), i] as const).sort((a, b) => b[0] - a[0]);
  const remainder = total - parts.reduce((a, b) => a + b, 0);
  for (let k = 0; k < remainder; k++) parts[order[k]![1]]!++;
  return parts;
}

async function main(): Promise<void> {
  const url = process.env.MIGRATION_DATABASE_URL;
  if (!url) throw new Error('MIGRATION_DATABASE_URL is not set (copy .env.example to .env).');
  if (process.env.NODE_ENV === 'production') throw new Error('Refusing to seed demo data in production.');
  const target = Number(process.env.SEED_ASSETS ?? 20_000);
  if (!Number.isInteger(target) || target < 0) throw new Error('SEED_ASSETS must be a whole number.');

  const connection = createDatabase(url, { max: 1, applicationName: 'ooh-seed-inventory' });
  try {
    const { db } = connection;
    const [demo] = await db.select({ id: tenant.id }).from(tenant).where(eq(tenant.slug, 'demo'));
    if (!demo) throw new Error('The demo company is missing: run `pnpm db:seed` first.');

    if (process.argv.includes('--remove')) {
      // No cascades on purpose: faces, mounts and assets go together, in one statement.
      const removed = await db.execute<{ n: number }>(sql`
        WITH victim AS (
          SELECT a.id FROM ooh_asset a WHERE a.tenant_id = ${demo.id} AND a.notes = ${MARKER}
            AND NOT EXISTS (SELECT 1 FROM asset_terms t WHERE t.asset_id = a.id)
            AND NOT EXISTS (SELECT 1 FROM asset_block b WHERE b.asset_id = a.id)
            AND NOT EXISTS (SELECT 1 FROM file_link l WHERE l.subject_type = 'asset' AND l.subject_id = a.id)
        ),
        faces AS (
          DELETE FROM advertising_face f USING mount_position m
          WHERE f.mount_position_id = m.id AND m.asset_id IN (SELECT id FROM victim)
        ),
        mounts AS (DELETE FROM mount_position m WHERE m.asset_id IN (SELECT id FROM victim)),
        gone AS (DELETE FROM ooh_asset a WHERE a.id IN (SELECT id FROM victim) RETURNING a.id)
        SELECT count(*)::int AS n FROM gone`);
      console.log(`✔ removed ${removed[0]?.n ?? 0} generated assets`);
      return;
    }

    const [{ existing } = { existing: 0 }] = await db
      .select({ existing: sql<number>`count(*)::int` })
      .from(oohAsset)
      .where(and(eq(oohAsset.tenantId, demo.id), eq(oohAsset.notes, MARKER)));
    const missing = target - existing;
    if (missing <= 0) {
      console.log(`✔ the demo company already has ${existing} generated assets (SEED_ASSETS=${target})`);
      return;
    }

    const types = (
      await db
        .select({ id: assetType.id, key: assetType.key, prefix: assetType.codePrefix })
        .from(assetType)
        .where(and(eq(assetType.tenantId, demo.id), eq(assetType.active, true)))
    ).filter((t) => t.key in TYPE_MIX);
    const perType = apportion(
      missing,
      types.map((t) => TYPE_MIX[t.key]!),
    );
    const started = Date.now();
    for (const [i, type] of types.entries()) {
      // Continue the type's numbering after the highest existing code (as the API does).
      const [{ last } = { last: null }] = await db
        .select({ last: sql<string | null>`max(${oohAsset.code})` })
        .from(oohAsset)
        .where(and(eq(oohAsset.tenantId, demo.id), sql`${oohAsset.code} ~ ${`^${type.prefix}-[0-9]{6}$`}`));
      let next = last ? Number(last.slice(type.prefix.length + 1)) + 1 : 1;
      const perCity = apportion(
        perType[i]!,
        CITIES.map((c) => c.weight),
      );
      for (const [j, c] of CITIES.entries()) {
        const n = perCity[j]!;
        if (n === 0) continue;
        // Two uniform draws make a centre-weighted (triangular) spread; ~85% active, 10% prospective,
        // 5% suspended (which needs a reason).
        await db.execute(sql`
          INSERT INTO ooh_asset (tenant_id, code, asset_type_id, lifecycle, suspend_reason, location, city, county, notes)
          SELECT ${demo.id}, ${type.prefix} || '-' || lpad((${next}::int + g - 1)::text, 6, '0'), ${type.id},
                 s.lifecycle::asset_lifecycle,
                 CASE WHEN s.lifecycle = 'SUSPENDED' THEN 'Structure under repair' END,
                 ST_SetSRID(ST_MakePoint(
                   ${c.lng}::float8 + (random() + random() - 1) * ${c.spread}::float8 * 1.4,
                   ${c.lat}::float8 + (random() + random() - 1) * ${c.spread}::float8), 4326)::geography,
                 ${c.city}, ${c.county}, ${MARKER}
          FROM generate_series(1, ${n}::int) g
          CROSS JOIN LATERAL (SELECT CASE WHEN g % 20 = 0 THEN 'SUSPENDED'
                                          WHEN g % 10 = 1 THEN 'PROSPECTIVE'
                                          ELSE 'ACTIVE' END AS lifecycle) s`);
        next += n;
      }
    }
    // Structure from each type's template, for generated assets that don't have it yet.
    await db.execute(sql`
      INSERT INTO mount_position (tenant_id, asset_id, position_no)
      SELECT a.tenant_id, a.id, p
      FROM ooh_asset a JOIN asset_type t ON t.id = a.asset_type_id
      CROSS JOIN LATERAL generate_series(1, t.default_mount_positions) p
      WHERE a.tenant_id = ${demo.id} AND a.notes = ${MARKER}
        AND NOT EXISTS (SELECT 1 FROM mount_position m WHERE m.asset_id = a.id)`);
    await db.execute(sql`
      INSERT INTO advertising_face (tenant_id, mount_position_id, face_code)
      SELECT m.tenant_id, m.id, chr(64 + f)
      FROM mount_position m JOIN ooh_asset a ON a.id = m.asset_id JOIN asset_type t ON t.id = a.asset_type_id
      CROSS JOIN LATERAL generate_series(1, t.faces_per_mount) f
      WHERE a.tenant_id = ${demo.id} AND a.notes = ${MARKER}
        AND NOT EXISTS (SELECT 1 FROM advertising_face x WHERE x.mount_position_id = m.id)`);
    await db.execute(sql`ANALYZE ooh_asset`);
    console.log(
      `✔ added ${missing} generated assets to the demo company (now ${target}) in ${((Date.now() - started) / 1000).toFixed(1)} s`,
    );
  } finally {
    await connection.close();
  }
}

if (process.argv[1]?.endsWith('seed-inventory.ts')) {
  main().catch((error: unknown) => {
    console.error('✖ inventory seed failed:', error);
    process.exit(1);
  });
}
